"""End-to-end encryption for AgentLink.

Per-agent X25519 keypair. The private key never leaves the agent's own
disk (``~/.agentlink/keys-<username>.json``, mode 0600). Only the public
key is registered with the relay.

1:1 content: ephemeral X25519 -> HKDF-SHA256 -> ChaCha20Poly1305.
The relay sees only the envelope {v, eph_pub, nonce, ct} — it stores and
routes ciphertext, and cannot read bodies, files, work instructions or
deliveries.

Group content: a random 256-bit group key, generated by the group
creator's client, wrapped (with the same 1:1 envelope scheme) for each
member, and ROTATED by a remaining admin's client whenever a member is
removed. Group frames carry {group_id, epoch, nonce, ct}.
"""

from __future__ import annotations

import base64
import json
import os
import secrets
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric.x25519 import (
    X25519PrivateKey,
    X25519PublicKey,
)
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

_INFO = b"agentlink-e2ee-v1"


def _b64(b: bytes) -> str:
    return base64.b64encode(b).decode()


def _unb64(s: str) -> bytes:
    return base64.b64decode(s)


class Identity:
    """An agent's local keypair, loaded from or created in state_dir."""

    def __init__(self, username: str, state_dir: str | Path):
        self.username = username
        self.path = Path(state_dir).expanduser() / f"keys-{username}.json"
        self.path.parent.mkdir(parents=True, exist_ok=True)
        if self.path.exists():
            data = json.loads(self.path.read_text())
            self._priv = X25519PrivateKey.from_private_bytes(
                _unb64(data["private_key"]))
        else:
            self._priv = X25519PrivateKey.generate()
            raw = self._priv.private_bytes(
                serialization.Encoding.Raw,
                serialization.PrivateFormat.Raw,
                serialization.NoEncryption())
            self.path.write_text(json.dumps(
                {"username": username, "private_key": _b64(raw),
                 "public_key": self.public_key_b64}))
            try:
                os.chmod(self.path, 0o600)
            except OSError:
                pass

    @classmethod
    def ephemeral(cls) -> "Identity":
        """In-memory keypair for one-shot (dial) clients; never persisted."""
        obj = cls.__new__(cls)
        obj.username = "ephemeral"
        obj.path = None
        obj._priv = X25519PrivateKey.generate()
        return obj

    @property
    def public_key_b64(self) -> str:
        raw = self._priv.public_key().public_bytes(
            serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        return _b64(raw)

    def _shared_key(self, peer_pub_b64: str) -> bytes:
        peer = X25519PublicKey.from_public_bytes(_unb64(peer_pub_b64))
        shared = self._priv.exchange(peer)
        return HKDF(algorithm=hashes.SHA256(), length=32,
                    salt=None, info=_INFO).derive(shared)

    # -- envelopes ------------------------------------------------------
    def encrypt_for(self, recipient_pub_b64: str, plaintext: bytes) -> dict:
        """Encrypt to a recipient's public key (ephemeral sender key)."""
        eph = X25519PrivateKey.generate()
        peer = X25519PublicKey.from_public_bytes(_unb64(recipient_pub_b64))
        shared = eph.exchange(peer)
        key = HKDF(algorithm=hashes.SHA256(), length=32,
                   salt=None, info=_INFO).derive(shared)
        nonce = secrets.token_bytes(12)
        ct = ChaCha20Poly1305(key).encrypt(nonce, plaintext, None)
        eph_pub = eph.public_key().public_bytes(
            serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        return {"v": 1, "alg": "x25519-chacha20poly1305",
                "eph_pub": _b64(eph_pub), "nonce": _b64(nonce),
                "ct": _b64(ct)}

    def decrypt_envelope(self, envelope: dict) -> bytes:
        key = self._shared_key(envelope["eph_pub"])
        return ChaCha20Poly1305(key).decrypt(
            _unb64(envelope["nonce"]), _unb64(envelope["ct"]), None)

    def wrap_key(self, recipient_pub_b64: str, key_bytes: bytes) -> dict:
        return self.encrypt_for(recipient_pub_b64, key_bytes)

    def unwrap_key(self, envelope: dict) -> bytes:
        return self.decrypt_envelope(envelope)


def encrypt_with_key(key: bytes, plaintext: bytes) -> dict:
    nonce = secrets.token_bytes(12)
    ct = ChaCha20Poly1305(key).encrypt(nonce, plaintext, None)
    return {"nonce": _b64(nonce), "ct": _b64(ct)}


def decrypt_with_key(key: bytes, envelope: dict) -> bytes:
    return ChaCha20Poly1305(key).decrypt(
        _unb64(envelope["nonce"]), _unb64(envelope["ct"]), None)


def new_group_key() -> bytes:
    return secrets.token_bytes(32)
