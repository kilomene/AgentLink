"""End-to-end encryption for AgentLink.

Per-agent X25519 keypair. The private key never leaves the agent's own
disk (``~/.agentlink/keys-<username>.json``, mode 0600). Only the public
key is registered with the relay.

1:1 content: ephemeral X25519 -> HKDF-SHA256 -> ChaCha20Poly1305.
The relay sees only the envelope {v, eph_pub, nonce, ct} — it stores and
routes ciphertext, and cannot read bodies, files, work instructions or
deliveries.

Group content: a random 256-bit group key, generated by the group
creator's client, wrapped (with the same 1:1 envelope scheme) for each
member, and ROTATED by a remaining admin's client whenever a member is
removed. Group frames carry {group_id, epoch, nonce, ct}.
"""

from __future__ import annotations

import base64
import json
import os
import secrets
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
    Ed25519PublicKey,
)
from cryptography.hazmat.primitives.asymmetric.x25519 import (
    X25519PrivateKey,
    X25519PublicKey,
)
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

_INFO = b"agentlink-e2ee-v1"


def _b64(b: bytes) -> str:
    return base64.b64encode(b).decode()


def _unb64(s: str) -> bytes:
    return base64.b64decode(s)


class Identity:
    """An agent's local keypair, loaded from or created in state_dir."""

    def __init__(self, username: str, state_dir: str | Path):
        self.username = username
        self.path = Path(state_dir).expanduser() / f"keys-{username}.json"
        self.keyring_path = (
            Path(state_dir).expanduser() / f"keyring-{username}.json")
        self.path.parent.mkdir(parents=True, exist_ok=True)
        if self.path.exists():
            data = json.loads(self.path.read_text())
            self._priv = X25519PrivateKey.from_private_bytes(
                _unb64(data["private_key"]))
            # Key epoch (2.6.1): pre-epoch files read as epoch 1.
            # Set BEFORE any _save below, so a re-save never
            # clobbers a recorded epoch with the default.
            self.key_epoch = int(data.get("key_epoch") or 1)
            if data.get("signing_private_key"):
                self._sign = Ed25519PrivateKey.from_private_bytes(
                    _unb64(data["signing_private_key"]))
            else:
                # Older keys file: add a signing key and re-save.
                self._sign = Ed25519PrivateKey.generate()
                self._save(data)
            if data.get("key_epoch") is None:
                self._save(data)
        else:
            self._priv = X25519PrivateKey.generate()
            self._sign = Ed25519PrivateKey.generate()
            self.key_epoch = 1
            self._save({})

    def _save(self, data: dict) -> None:
        if self.path is None:
            return
        raw = self._priv.private_bytes(
            serialization.Encoding.Raw,
            serialization.PrivateFormat.Raw,
            serialization.NoEncryption())
        sraw = self._sign.private_bytes(
            serialization.Encoding.Raw,
            serialization.PrivateFormat.Raw,
            serialization.NoEncryption())
        data.update({"username": self.username,
                     "private_key": _b64(raw),
                     "public_key": self.public_key_b64,
                     "signing_private_key": _b64(sraw),
                     "signing_public_key": self.signing_public_key_b64,
                     "key_epoch": int(getattr(
                         self, "key_epoch", 1) or 1)})
        self.path.write_text(json.dumps(data))
        try:
            os.chmod(self.path, 0o600)
        except OSError:
            pass

    @classmethod
    def ephemeral(cls) -> "Identity":
        """In-memory keypair for one-shot (dial) clients; never persisted."""
        obj = cls.__new__(cls)
        obj.username = "ephemeral"
        obj.path = None
        obj.keyring_path = None
        obj.key_epoch = 1
        obj._priv = X25519PrivateKey.generate()
        obj._sign = Ed25519PrivateKey.generate()
        return obj

    # -- keyring (2.6.1): retained prior encryption keys -----------
    # Rotation must never orphan delivered-but-unread mail: the
    # prior encryption private key is archived here (mode 600)
    # before the fresh key takes over, and decryption tries the
    # current key first, then the retired keys newest-first.

    def _load_keyring(self) -> list[dict]:
        """The retired-key list (empty for ephemeral identities,
        which hold no durable state and write no files)."""
        if self.keyring_path is None:
            return []
        try:
            data = json.loads(self.keyring_path.read_text())
            retired = data.get("retired") or []
            if isinstance(retired, list):
                return [dict(r) for r in retired
                        if isinstance(r, dict)
                        and r.get("private_key")]
        except FileNotFoundError:
            pass
        except Exception:
            pass
        return []

    def _save_keyring(self, retired: list[dict]) -> None:
        if self.keyring_path is None:
            return
        self.keyring_path.write_text(json.dumps(
            {"retired": list(retired)}))
        try:
            os.chmod(self.keyring_path, 0o600)
        except OSError:
            pass

    def _raw_private(self) -> bytes:
        return self._priv.private_bytes(
            serialization.Encoding.Raw,
            serialization.PrivateFormat.Raw,
            serialization.NoEncryption())

    def archive_current_key(self) -> bool:
        """Archive the CURRENT encryption private key under its
        epoch in the keyring. No-op (False) for ephemeral
        identities and when this epoch is already archived.
        True when a new entry was written."""
        if self.keyring_path is None:
            return False
        import time as _time
        retired = self._load_keyring()
        epoch = int(self.key_epoch or 1)
        if any(int(r.get("key_epoch") or 0) == epoch
               for r in retired):
            return False
        retired.append({"key_epoch": epoch,
                        "private_key": _b64(self._raw_private()),
                        "retired_at": int(_time.time())})
        self._save_keyring(retired)
        return True

    def _decrypt_with_priv(self, priv: X25519PrivateKey,
                           envelope: dict) -> bytes:
        peer = X25519PublicKey.from_public_bytes(
            _unb64(envelope["eph_pub"]))
        shared = priv.exchange(peer)
        key = HKDF(algorithm=hashes.SHA256(), length=32,
                   salt=None, info=_INFO).derive(shared)
        return ChaCha20Poly1305(key).decrypt(
            _unb64(envelope["nonce"]), _unb64(envelope["ct"]), None)

    def decrypt_any(self, envelope: dict) -> tuple[bytes, int]:
        """Open an envelope with the current key first, then the
        retired keys newest-first. Returns (plaintext,
        epoch_used). Raises when no held key opens it."""
        try:
            return (self.decrypt_envelope(envelope),
                    int(self.key_epoch or 1))
        except Exception:
            pass
        last_exc: Exception | None = None
        retired = sorted(
            self._load_keyring(),
            key=lambda r: int(r.get("key_epoch") or 0),
            reverse=True)
        for entry in retired:
            try:
                priv = X25519PrivateKey.from_private_bytes(
                    _unb64(str(entry["private_key"])))
                return (self._decrypt_with_priv(priv, envelope),
                        int(entry.get("key_epoch") or 0))
            except Exception as exc:
                last_exc = exc
                continue
        if last_exc is not None:
            raise last_exc
        raise ValueError("no key available to open the envelope")

    def rotate_encryption_key(self) -> int:
        """Rotate the ENCRYPTION key only (the signing key is
        untouched, so the session and the account identity
        survive): archive the current key, generate a fresh
        X25519 pair, bump the epoch, persist. Returns the new
        epoch. Ephemeral identities rotate in memory only and
        write no files."""
        self.archive_current_key()
        self._priv = X25519PrivateKey.generate()
        self.key_epoch = int(self.key_epoch or 1) + 1
        self._save({})
        return self.key_epoch

    def restore_retired_key(self, epoch: int) -> bool:
        """Restore a retired encryption key to current (the
        rotation-rollback used when a rebind fails after the
        local rotation already landed): the keyring entry for
        ``epoch`` becomes the current key and the epoch steps
        back to it. False when no such entry exists."""
        epoch = int(epoch)
        for entry in self._load_keyring():
            if int(entry.get("key_epoch") or 0) != epoch:
                continue
            self._priv = X25519PrivateKey.from_private_bytes(
                _unb64(str(entry["private_key"])))
            self.key_epoch = epoch
            self._save({})
            return True
        return False

    @property
    def signing_public_key_b64(self) -> str:
        raw = self._sign.public_key().public_bytes(
            serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        return _b64(raw)

    def sign(self, payload: bytes) -> str:
        """Ed25519 signature (base64) — used for signed delivery proof."""
        return _b64(self._sign.sign(payload))

    @staticmethod
    def verify_signature(sign_pub_b64: str, payload: bytes,
                         signature_b64: str) -> bool:
        try:
            pub = Ed25519PublicKey.from_public_bytes(_unb64(sign_pub_b64))
            pub.verify(_unb64(signature_b64), payload)
            return True
        except Exception:
            return False

    @property
    def public_key_b64(self) -> str:
        raw = self._priv.public_key().public_bytes(
            serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        return _b64(raw)

    def _shared_key(self, peer_pub_b64: str) -> bytes:
        peer = X25519PublicKey.from_public_bytes(_unb64(peer_pub_b64))
        shared = self._priv.exchange(peer)
        return HKDF(algorithm=hashes.SHA256(), length=32,
                    salt=None, info=_INFO).derive(shared)

    # -- envelopes ------------------------------------------------------
    def encrypt_for(self, recipient_pub_b64: str, plaintext: bytes) -> dict:
        """Encrypt to a recipient's public key (ephemeral sender key)."""
        return encrypt_to_pubkey(recipient_pub_b64, plaintext)

    def decrypt_envelope(self, envelope: dict) -> bytes:
        key = self._shared_key(envelope["eph_pub"])
        return ChaCha20Poly1305(key).decrypt(
            _unb64(envelope["nonce"]), _unb64(envelope["ct"]), None)

    def wrap_key(self, recipient_pub_b64: str, key_bytes: bytes) -> dict:
        return self.encrypt_for(recipient_pub_b64, key_bytes)

    def unwrap_key(self, envelope: dict) -> bytes:
        return self.decrypt_envelope(envelope)


def encrypt_to_pubkey(recipient_pub_b64: str, plaintext: bytes) -> dict:
    """Ephemeral-sender encryption to a bare X25519 public key — the
    exact scheme of :meth:`Identity.encrypt_for`, usable without an
    Identity (the sender needs no identity to seal TO a key)."""
    eph = X25519PrivateKey.generate()
    peer = X25519PublicKey.from_public_bytes(_unb64(recipient_pub_b64))
    shared = eph.exchange(peer)
    key = HKDF(algorithm=hashes.SHA256(), length=32,
               salt=None, info=_INFO).derive(shared)
    nonce = secrets.token_bytes(12)
    ct = ChaCha20Poly1305(key).encrypt(nonce, plaintext, None)
    eph_pub = eph.public_key().public_bytes(
        serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    return {"v": 1, "alg": "x25519-chacha20poly1305",
            "eph_pub": _b64(eph_pub), "nonce": _b64(nonce),
            "ct": _b64(ct)}


# -- owner oversight (2026-11-01, owner's direct order) -------------------
# The operator holds an OVERSIGHT keypair. Its PUBLIC key is public
# config (relay-advertised in the welcome frame, or the client env
# AGENTLINK_OVERSIGHT_PUBKEY); its PRIVATE key never leaves the
# operator's dashboard host. Clients seal an extra copy of every
# content payload (or of the symmetric content key) to the oversight
# public key and attach it to the frame as ``oversight`` — the relay
# stores/routes that wrap as ciphertext, exactly like all other
# content, and can never open it. Only the dashboard, holding the
# private key, can.
#
# Oversight key file format (written by `agentlink oversight-keygen`,
# loaded by the dashboard via env AGENTLINK_OVERSIGHT_KEY_FILE) — a
# single JSON object, file mode 0600:
#   {"kind": "agentlink-oversight-key", "version": 1,
#    "private_key": "<base64 raw 32-byte X25519 private key>",
#    "public_key":  "<base64 raw 32-byte X25519 public key>",
#    "created_at":  <epoch seconds>}

OVERSIGHT_KEY_KIND = "agentlink-oversight-key"
OVERSIGHT_KEY_VERSION = 1


class OversightKey:
    """The operator's oversight keypair (dashboard side)."""

    def __init__(self, priv: X25519PrivateKey):
        self._priv = priv

    @classmethod
    def generate(cls) -> "OversightKey":
        return cls(X25519PrivateKey.generate())

    @property
    def public_key_b64(self) -> str:
        raw = self._priv.public_key().public_bytes(
            serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        return _b64(raw)

    def _raw_private(self) -> bytes:
        return self._priv.private_bytes(
            serialization.Encoding.Raw,
            serialization.PrivateFormat.Raw,
            serialization.NoEncryption())

    def save(self, path: str | Path) -> Path:
        import time as _time
        p = Path(path).expanduser()
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps({
            "kind": OVERSIGHT_KEY_KIND,
            "version": OVERSIGHT_KEY_VERSION,
            "private_key": _b64(self._raw_private()),
            "public_key": self.public_key_b64,
            "created_at": int(_time.time())}))
        try:
            os.chmod(p, 0o600)
        except OSError:
            pass
        return p

    @classmethod
    def load(cls, path: str | Path) -> "OversightKey":
        data = json.loads(Path(path).expanduser().read_text())
        if data.get("kind") != OVERSIGHT_KEY_KIND:
            raise ValueError(f"{path}: not an oversight key file")
        return cls(X25519PrivateKey.from_private_bytes(
            _unb64(data["private_key"])))

    def decrypt_envelope(self, envelope: dict) -> bytes:
        """Open one oversight wrap (the encrypt_for envelope shape)."""
        peer = X25519PublicKey.from_public_bytes(
            _unb64(envelope["eph_pub"]))
        shared = self._priv.exchange(peer)
        key = HKDF(algorithm=hashes.SHA256(), length=32,
                   salt=None, info=_INFO).derive(shared)
        return ChaCha20Poly1305(key).decrypt(
            _unb64(envelope["nonce"]), _unb64(envelope["ct"]), None)

    def open_content(self, envelope: dict) -> dict:
        """Wrap kind 'content': the wrapped plaintext is the content
        payload JSON (1:1 messages, work assignments/deliveries)."""
        return json.loads(self.decrypt_envelope(envelope))

    def open_key(self, envelope: dict) -> bytes:
        """Wrap kind 'content_key': the wrapped plaintext is the raw
        symmetric content key (group/channel key, or a file key) that
        decrypts the sibling content envelope via decrypt_with_key."""
        return self.decrypt_envelope(envelope)


def encrypt_with_key(key: bytes, plaintext: bytes,
                     nonce: bytes | None = None) -> dict:
    nonce = nonce or secrets.token_bytes(12)
    ct = ChaCha20Poly1305(key).encrypt(nonce, plaintext, None)
    return {"nonce": _b64(nonce), "ct": _b64(ct)}


def decrypt_with_key(key: bytes, envelope: dict) -> bytes:
    return ChaCha20Poly1305(key).decrypt(
        _unb64(envelope["nonce"]), _unb64(envelope["ct"]), None)


def new_group_key() -> bytes:
    return secrets.token_bytes(32)
