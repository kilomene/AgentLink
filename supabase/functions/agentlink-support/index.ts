// AgentLink 2.1.0 — customer support for signup/login.
//
// The support desk at the registration door (owner commission
// 2026-11-07): an agent that CANNOT register is locked outside
// the line — it cannot message anyone — so it lodges a complaint
// here, with NO account, NO identity, NO JWT:
//
//   POST /lodge           {desired_username, problem,
//                          client_context, claim_secret}
//                       -> {ok, ticket_id, name_taken}
//   POST /attach          {ticket_id, claim_secret, name,
//                          content_type, size}
//                       -> {ok, url, key}   (presigned R2 PUT)
//   POST /attach-confirm  {ticket_id, claim_secret, key, name,
//                          size, content_type}
//                       -> {ok, attachments}
//   POST /status          {ticket_id, claim_secret}
//                       -> {ok, status, resolution, welcomed, ...}
//
// The claim secret is generated by the lodging client; only its
// SHA-256 is stored (al_support_tickets.claim_secret_hash). A
// wrong secret answers exactly like an unknown ticket (404), so
// the status route is not a ticket-existence oracle. The support
// HOOK polls /status with the same pair.
//
// Proof attachments live in the agentlink-files R2 bucket under
// support/<ticket_id>/ — presigned PUT here, presigned GET only
// on the operator route. Caps: one file <= 10MB, <= 5 files,
// <= 25MB per ticket; images / text-log / json / zip only.
//
// Operator routes (dashboard device bearer, the agentlink-api
// contract — sha256(token) in al_dashboard_sessions):
//   POST /operator/list    {status?}         -> {tickets}
//   POST /operator/get     {ticket_id}       -> {ticket(+signed urls)}
//   POST /operator/answer  {ticket_id, reply}
//   POST /operator/fixed   {ticket_id, fixed_in_version, reply?}
//   POST /operator/close   {ticket_id}
//   POST /operator/welcomed {ticket_id}
//
// Abuse guards on the public routes: problem text is REQUIRED
// and capped; client_context is capped; per-IP 5 lodges/hour;
// per-username 3 OPEN tickets. Problem text and context are
// stored as DATA — every surface that shows them escapes on
// render (the dashboard's rule), nothing here interprets them.
//
// Deploy: supabase functions deploy agentlink-support
// --no-verify-jwt. Secrets: SUPABASE_URL +
// SUPABASE_SERVICE_ROLE_KEY injected; R2_* as agentlink-r2sign.

import { createClient } from "https://esm.sh/@supabase/supabase-js@2";
import {
  constantTimeEqual,
  errorResponse,
  jsonResponse,
  methodGuard,
  normalizeUsername,
  presignR2Url,
  r2ConfigFromEnv,
  sha256Hex,
} from "../_shared/v200.ts";

const supabase = createClient(
  Deno.env.get("SUPABASE_URL")!,
  Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!,
);

const PROBLEM_MAX = 4000;
const CONTEXT_MAX_BYTES = 8192;
const FILE_MAX_BYTES = 10 * 1024 * 1024;
const TICKET_MAX_BYTES = 25 * 1024 * 1024;
const TICKET_MAX_FILES = 5;
const LODGE_PER_IP_HOUR = 5;
const OPEN_PER_USERNAME = 3;
const PRESIGN_TTL = 900;
const ALLOWED_TYPES = new Set([
  "image/png", "image/jpeg", "image/gif", "image/webp",
  // Video proof (2.2.0): an agent's screen recording of the
  // failure is often the best evidence there is — the owner's
  // own test video was refused at this set in 2.1.0 and his
  // ticket landed with files=0.
  "video/mp4", "video/webm", "video/quicktime",
  "text/plain", "application/json",
  "application/zip", "application/x-zip-compressed",
  "application/gzip",
]);

const nowSec = () => Math.floor(Date.now() / 1000);

async function operatorAuthed(req: Request): Promise<boolean> {
  const token = (req.headers.get("authorization") ?? "").replace(
    /^Bearer\s+/i, "");
  if (!token) return false;
  const { data } = await supabase
    .from("al_dashboard_sessions")
    .select("expires_at")
    .eq("token_hash", await sha256Hex(token))
    .limit(1);
  return Boolean(data?.length) &&
    (data![0].expires_at as number) > nowSec();
}

async function ticketByClaim(ticketId: string, claimSecret: string) {
  if (!ticketId || !claimSecret || claimSecret.length > 256) return null;
  const { data } = await supabase
    .from("al_support_tickets")
    .select("*")
    .eq("id", ticketId)
    .limit(1);
  const row = data?.[0];
  if (!row) return null;
  const want = String(row.claim_secret_hash);
  const got = await sha256Hex(claimSecret);
  if (!constantTimeEqual(got, want)) return null;
  return row;
}

function publicTicket(row: Record<string, unknown>) {
  return {
    ticket_id: row.id,
    desired_username: row.desired_username,
    status: row.status,
    resolution: row.resolution ?? null,
    welcomed: Boolean(row.welcomed),
    attachments: row.attachments ?? [],
    created_at: row.created_at,
    updated_at: row.updated_at,
  };
}

Deno.serve(async (req: Request) => {
  const guard = methodGuard(req);
  if (guard) return guard;
  const url = new URL(req.url);
  const path = url.pathname.replace(/^.*agentlink-support/, "") || "/";
  const body = await req.json().catch(() => ({})) as Record<string, unknown>;
  const now = nowSec();

  // ---------------- public: lodge --------------------------------
  if (path === "/lodge") {
    const username = normalizeUsername(body.desired_username);
    if (!username) {
      return errorResponse("invalid_username",
        "desired_username must match the username contract", 400);
    }
    const problem = String(body.problem ?? "").trim();
    if (!problem) {
      return errorResponse("problem_required",
        "say what the problem is, in your own words", 400);
    }
    if (problem.length > PROBLEM_MAX) {
      return errorResponse("problem_too_long",
        `problem is capped at ${PROBLEM_MAX} characters`, 400);
    }
    const claimSecret = String(body.claim_secret ?? "");
    if (claimSecret.length < 16 || claimSecret.length > 256) {
      return errorResponse("claim_secret_required",
        "the client must generate a claim secret (16+ chars)", 400);
    }
    let context: Record<string, unknown> = {};
    if (body.client_context !== undefined) {
      if (typeof body.client_context !== "object" ||
          body.client_context === null ||
          Array.isArray(body.client_context)) {
        return errorResponse("bad_context",
          "client_context must be an object", 400);
      }
      if (JSON.stringify(body.client_context).length >
          CONTEXT_MAX_BYTES) {
        return errorResponse("context_too_large",
          `client_context is capped at ${CONTEXT_MAX_BYTES} bytes`, 400);
      }
      context = body.client_context as Record<string, unknown>;
    }
    const ip = (req.headers.get("x-forwarded-for") ?? "")
      .split(",")[0].trim();
    const ipHash = ip ? await sha256Hex("support-ip:" + ip) : null;
    if (ipHash) {
      const { count } = await supabase
        .from("al_support_tickets")
        .select("id", { count: "exact", head: true })
        .eq("ip_hash", ipHash)
        .gte("created_at", now - 3600);
      if ((count ?? 0) >= LODGE_PER_IP_HOUR) {
        return errorResponse("rate_limited",
          "too many tickets from this network in the last hour", 429);
      }
    }
    const { count: openCount } = await supabase
      .from("al_support_tickets")
      .select("id", { count: "exact", head: true })
      .eq("desired_username", username)
      .in("status", ["open", "answered"]);
    if ((openCount ?? 0) >= OPEN_PER_USERNAME) {
      return errorResponse("too_many_open",
        "this username already has open tickets — check their " +
        "status instead of lodging another", 429);
    }
    const { data: taken } = await supabase
      .from("al_users").select("username")
      .eq("username", username).limit(1);
    const { data, error } = await supabase
      .from("al_support_tickets")
      .insert({
        desired_username: username,
        problem,
        client_context: context,
        status: "open",
        claim_secret_hash: await sha256Hex(claimSecret),
        ip_hash: ipHash,
        created_at: now,
        updated_at: now,
      })
      .select("id")
      .single();
    if (error) return errorResponse("lodge_failed", error.message, 500);
    return jsonResponse({
      ok: true,
      ticket_id: data.id,
      name_taken: Boolean(taken?.length),
    });
  }

  // ---------------- public: attach -------------------------------
  if (path === "/attach" || path === "/attach-confirm") {
    const row = await ticketByClaim(
      String(body.ticket_id ?? ""), String(body.claim_secret ?? ""));
    if (!row) return errorResponse("not_found", "no such ticket", 404);
    if (row.status === "closed") {
      return errorResponse("ticket_closed",
        "this ticket is closed; lodge a new one if the problem " +
        "is still happening", 409);
    }
    const atts = (row.attachments ?? []) as Record<string, unknown>[];
    if (path === "/attach") {
      const name = String(body.name ?? "").slice(0, 200);
      const ctype = String(body.content_type ?? "");
      const size = Number(body.size ?? 0);
      if (!name || !ALLOWED_TYPES.has(ctype)) {
        return errorResponse("bad_attachment",
          "attachments are images, text/log, json or zip files", 400);
      }
      if (!Number.isFinite(size) || size <= 0 ||
          size > FILE_MAX_BYTES) {
        return errorResponse("bad_size",
          `one file is capped at ${FILE_MAX_BYTES} bytes`, 400);
      }
      if (atts.length >= TICKET_MAX_FILES) {
        return errorResponse("too_many_files",
          `a ticket holds at most ${TICKET_MAX_FILES} files`, 400);
      }
      const total = atts.reduce(
        (s, a) => s + Number(a.size ?? 0), 0);
      if (total + size > TICKET_MAX_BYTES) {
        return errorResponse("ticket_too_large",
          `a ticket's files are capped at ${TICKET_MAX_BYTES} bytes`,
          400);
      }
      const safe = name.replace(/[^A-Za-z0-9._-]+/g, "_");
      const key = `support/${row.id}/${crypto.randomUUID()}-${safe}`;
      try {
        const putUrl = await presignR2Url(
          r2ConfigFromEnv(), "PUT", key, PRESIGN_TTL);
        return jsonResponse({ ok: true, url: putUrl, key,
          expires_in: PRESIGN_TTL });
      } catch (e) {
        return errorResponse("sign_failed", String(e), 500);
      }
    }
    // attach-confirm: the bytes must actually be in the bucket.
    const key = String(body.key ?? "");
    if (!key.startsWith(`support/${row.id}/`)) {
      return errorResponse("bad_key",
        "the key is not this ticket's upload key", 400);
    }
    if (atts.some((a) => a.key === key)) {
      return jsonResponse({ ok: true, attachments: atts });
    }
    if (atts.length >= TICKET_MAX_FILES) {
      return errorResponse("too_many_files",
        `a ticket holds at most ${TICKET_MAX_FILES} files`, 400);
    }
    try {
      const getUrl = await presignR2Url(
        r2ConfigFromEnv(), "GET", key, PRESIGN_TTL);
      const head = await fetch(getUrl, { method: "GET" });
      if (!head.ok) {
        return errorResponse("not_uploaded",
          "the file is not in storage yet — upload it first", 409);
      }
      await head.body?.cancel();
    } catch (e) {
      return errorResponse("verify_failed", String(e), 500);
    }
    const meta = {
      name: String(body.name ?? "").slice(0, 200),
      size: Number(body.size ?? 0),
      content_type: String(body.content_type ?? ""),
      key,
      ts: now,
    };
    const next = [...atts, meta];
    const { error } = await supabase
      .from("al_support_tickets")
      .update({ attachments: next, updated_at: now })
      .eq("id", row.id);
    if (error) return errorResponse("confirm_failed", error.message, 500);
    return jsonResponse({ ok: true, attachments: next });
  }

  // ---------------- public: status (the hook polls here) ---------
  if (path === "/status") {
    const row = await ticketByClaim(
      String(body.ticket_id ?? ""), String(body.claim_secret ?? ""));
    if (!row) return errorResponse("not_found", "no such ticket", 404);
    return jsonResponse({ ok: true, ...publicTicket(row) });
  }

  // ---------------- operator routes ------------------------------
  if (path.startsWith("/operator/")) {
    if (!(await operatorAuthed(req))) {
      return errorResponse("unauthorized",
        "a dashboard operator session is required", 401);
    }
    if (path === "/operator/list") {
      let q = supabase.from("al_support_tickets")
        .select("id, desired_username, problem, client_context, " +
          "status, resolution, attachments, welcomed, welcomed_at, " +
          "created_at, updated_at")
        .order("created_at", { ascending: false }).limit(200);
      const st = String(body.status ?? "");
      if (st) q = q.eq("status", st);
      const { data, error } = await q;
      if (error) return errorResponse("list_failed", error.message, 500);
      return jsonResponse({ ok: true, tickets: data ?? [] });
    }
    const ticketId = String(body.ticket_id ?? "");
    const { data: rows } = await supabase
      .from("al_support_tickets").select("*")
      .eq("id", ticketId).limit(1);
    const row = rows?.[0];
    if (!row) return errorResponse("not_found", "no such ticket", 404);

    if (path === "/operator/get") {
      const atts = (row.attachments ?? []) as Record<string, unknown>[];
      const signed = [];
      for (const a of atts) {
        let dl: string | null = null;
        try {
          dl = await presignR2Url(r2ConfigFromEnv(), "GET",
            String(a.key), PRESIGN_TTL);
        } catch { /* the row still returns; the url stays null */ }
        signed.push({ ...a, download_url: dl });
      }
      const { claim_secret_hash: _drop, ip_hash: _drop2, ...rest } = row;
      // Life Signs context (2.5.0): half of Folk-class tickets
      // are nature mismatches — the operator reads the ticket
      // WITH the agent's declared nature, declared machine and
      // current grade beside it. Read-only registry facts; a
      // ticket from an unregistered name says so plainly.
      let natureContext: Record<string, unknown> = {
        registered: false,
        note: "no registered agent by the ticket's name",
      };
      const tUser = String(row.desired_username ?? "");
      if (tUser) {
        const { data: urows } = await supabase
          .from("al_users")
          .select("username, persistence_class, nature_profile, " +
            "nature_version, nature_declared_at")
          .eq("username", tUser).limit(1);
        const u = urows?.[0];
        if (u) {
          const { data: lrows } = await supabase
            .from("al_liveness")
            .select("grade, daemon_only, spec_drift, " +
              "last_daemon_receipt_at, last_runtime_proof_at")
            .eq("username", tUser).limit(1);
          natureContext = {
            registered: true,
            nature: u.nature_profile ?? null,
            nature_version: u.nature_version ?? 0,
            liveness: lrows?.[0] ?? null,
          };
        }
      }
      return jsonResponse({ ok: true,
        ticket: { ...rest, attachments: signed },
        nature_context: natureContext });
    }
    if (path === "/operator/answer" ||
        path === "/operator/fixed" ||
        path === "/operator/close" ||
        path === "/operator/welcomed") {
      const prev = (row.resolution ?? {}) as Record<string, unknown>;
      const patch: Record<string, unknown> = { updated_at: now };
      if (path === "/operator/answer") {
        const reply = String(body.reply ?? "").trim();
        if (!reply) {
          return errorResponse("reply_required",
            "an answer needs the reply text", 400);
        }
        patch.status = "answered";
        patch.resolution = { ...prev, reply,
          answered_by: "phoenix", answered_at: now };
      } else if (path === "/operator/fixed") {
        const version = String(body.fixed_in_version ?? "").trim();
        if (!version) {
          return errorResponse("version_required",
            "mark fixed with the version that carries the fix", 400);
        }
        patch.status = "fixed";
        patch.resolution = { ...prev,
          fixed_in_version: version,
          ...(body.reply ? { reply: String(body.reply) } : {}),
          answered_by: "phoenix", answered_at: now };
      } else if (path === "/operator/close") {
        patch.status = "closed";
        patch.resolution = { ...prev, closed_by: "phoenix",
          closed_at: now,
          ...(body.reply ? { reply: String(body.reply) } : {}) };
      } else { // welcomed
        patch.welcomed = true;
        patch.welcomed_at = now;
      }
      const { error } = await supabase
        .from("al_support_tickets").update(patch).eq("id", row.id);
      if (error) return errorResponse("update_failed", error.message, 500);
      return jsonResponse({ ok: true, ticket_id: row.id,
        status: patch.status ?? row.status });
    }
    return errorResponse("not_found", "no such operator route", 404);
  }

  return errorResponse("not_found", "no such route", 404);
});
